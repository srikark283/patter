import assert from 'node:assert/strict';
import { buildSync } from 'esbuild';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const require = createRequire(import.meta.url);
const output = buildSync({ entryPoints: ['src/features/dashboard/components/BuiltInModelSettings.tsx'], bundle: true, write: false, platform: 'node', format: 'cjs', packages: 'external', alias: { '@': resolve('src') } });
const module = { exports: {} };
new Function('require', 'module', 'exports', output.outputFiles[0].text)(require, module, module.exports);
const props = { model: 'patter-1-nano', settings: { cleanup_provider: 'built_in', built_in_model: 'patter-1-nano', llm_cleanup_enabled: true, language: 'en', app_profiles: [] }, status: { supported: true, installed: true, runtime_ready: true, version: 'patter-1-nano-current', previous_version: 'patter-flash-v1' }, busy: false, error: '', onEnable() {}, onRefresh() {} };
const render = p => renderToStaticMarkup(React.createElement(module.exports.BuiltInModelSettings, p));
const retired = render(props);
assert(!retired.includes('patter-flash'));
assert(!retired.includes('cleanup is enabled'));
assert(!retired.includes('By Patter'));
assert(retired.includes('Model maintenance'));
assert(!retired.includes('Try your text'));
assert(render({ ...props, status: { ...props.status, previous_version: 'patter-1-nano-previous' } }).includes('Restore previous'));
assert(!render({ ...props, status: { ...props.status, previous_version: null } }).includes('Restore'));
assert(render({ ...props, status: { ...props.status, runtime_ready: false } }).includes('runtime missing'));
console.log('Built-in settings: retired restore hidden, valid restore retained, duplicate details removed, errors visible.');

const mini = render({ ...props, model: 'patter-1-mini', settings: { ...props.settings, built_in_model: 'patter-1-mini' }, status: { ...props.status, installed: false } });
assert(!mini.includes('Local MLX export folder'));
assert(mini.includes('Download &amp; enable patter-1-mini'));
assert(!mini.includes('pending'));
assert(!mini.includes('Gemma Terms'));
assert(!mini.includes('Model maintenance'));
console.log('Mini setup: public download offered, no local-folder requirement, nano updates, or Gemma terms.');

const playgroundBundle = buildSync({ entryPoints: ['src/features/dashboard/components/CleanupPlayground.tsx'], bundle: true, write: false, platform: 'node', format: 'cjs', packages: 'external', alias: { '@': resolve('src') } });
const playground = { exports: {} };
new Function('require', 'module', 'exports', playgroundBundle.outputFiles[0].text)(require, playground, playground.exports);
const preview = statuses => renderToStaticMarkup(React.createElement(playground.exports.CleanupPlayground, { settings: props.settings, statuses, busy: false }));
assert(preview({}).includes('Try your text'));
assert(preview({}).includes('Download this model'));
const readyPreview = preview({ 'patter-1-nano': props.status });
assert(readyPreview.includes('Test model'));
assert(readyPreview.includes('Your default stays unchanged'));
assert(!readyPreview.includes('Model maintenance'));
console.log('Cleanup playground: independent model selector, visible without Manage, no activation or maintenance controls.');
